"""Integration contracts used by application services."""
from abc import ABC, abstractmethod
from typing import Protocol


class HardwareBackend(ABC):
    @property
    @abstractmethod
    def available(self) -> bool: ...

    @abstractmethod
    def status(self) -> dict: ...

    @abstractmethod
    def set(self, operation: str, *values) -> None: ...

    @abstractmethod
    def fan_status(self) -> dict: ...


class ControllerIntegration(Protocol):
    def input_profiles(self) -> list: ...
    def controller_plans(self, obj=None) -> dict: ...
    def configure_input(self) -> None: ...


class DesktopIntegration(Protocol):
    name: str
    def supports(self, feature: str) -> bool: ...
    def install_placement(self, prefs: dict, displays: dict) -> bool: ...
    def list_windows(self) -> bool: ...
    def move_window(self, identity: str, output: str) -> bool: ...
    def activate_window(self, identity: str) -> bool: ...
